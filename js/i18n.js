function getCurrentLang() {
  return localStorage.getItem('kisanLang') || 'en';
}

function setLanguage(langCode) {
  if (translations[langCode]) {
    localStorage.setItem('kisanLang', langCode);
    
    // Dispatch a custom event to notify components/renderers
    const event = new CustomEvent('kisanLanguageChanged', { detail: { lang: langCode } });
    window.dispatchEvent(event);
    
    applyTranslations();
  }
}

function t(key) {
  const currentLang = getCurrentLang();
  return translations[currentLang]?.[key] || translations['en']?.[key] || key;
}

function applyTranslations() {
  // Update all elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });

  // Update placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = t(key);
  });
}

